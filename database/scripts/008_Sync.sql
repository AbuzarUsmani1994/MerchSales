/*
  008_Sync.sql
  Mobile devices, the command log that makes uploads idempotent, number ranges issued
  to devices for offline receipts, tombstones for hard deletes, and the minimum app
  version policy.

  Delta download rule: every synced table has RowVer and an index on (TenantId, RowVer).
  The app sends the last token it received; the API returns rows with RowVer > token and
  a new token = MIN_ACTIVE_ROWVERSION() - 1 captured BEFORE reading (never miss a row
  committed during the read). Deleted rows are reported from sync.Tombstone.
*/
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
GO
SET NOCOUNT ON;
SET XACT_ABORT ON;

IF EXISTS (SELECT 1 FROM dbo.SchemaVersion WHERE ScriptName = N'008_Sync')
BEGIN
    PRINT N'008_Sync already applied - skipped.';
    RETURN;
END;

BEGIN TRY
    BEGIN TRANSACTION;

    CREATE TABLE sync.Device
    (
        TenantId            uniqueidentifier NOT NULL,
        Id                  uniqueidentifier NOT NULL,   -- generated by the app on first install
        ClusterKey          bigint IDENTITY(1,1) NOT NULL,
        UserId              uniqueidentifier NOT NULL,   -- last user signed in on the device
        BranchId            uniqueidentifier NULL,
        Platform            varchar(10)      NOT NULL,
        DeviceName          nvarchar(100)    NULL,
        AppVersion          varchar(20)      NULL,
        OsVersion           varchar(40)      NULL,
        PushToken           nvarchar(500)    NULL,       -- FCM registration token
        RegisteredAtUtc     datetime2(3)     NOT NULL CONSTRAINT DF_Device_RegisteredAtUtc DEFAULT SYSUTCDATETIME(),
        LastSeenAtUtc       datetime2(3)     NULL,
        LastSyncAtUtc       datetime2(3)     NULL,
        IsRevoked           bit              NOT NULL CONSTRAINT DF_Device_Revoked DEFAULT 0,
        RevokedAtUtc        datetime2(3)     NULL,
        RevokedBy           uniqueidentifier NULL,
        WipeRequested       bit              NOT NULL CONSTRAINT DF_Device_Wipe DEFAULT 0, -- app deletes local data on next contact
        RowVer              rowversion       NOT NULL,
        CONSTRAINT PK_Device PRIMARY KEY NONCLUSTERED (Id),
        CONSTRAINT UQ_Device_TenantId_Id UNIQUE NONCLUSTERED (TenantId, Id),
        CONSTRAINT FK_Device_User FOREIGN KEY (TenantId, UserId) REFERENCES [identity].[User] (TenantId, Id),
        CONSTRAINT FK_Device_Branch FOREIGN KEY (TenantId, BranchId) REFERENCES tenancy.Branch (TenantId, Id),
        CONSTRAINT CK_Device_Platform CHECK (Platform IN ('Android','iOS'))
    );
    CREATE UNIQUE CLUSTERED INDEX CX_Device ON sync.Device (TenantId, ClusterKey);

    ALTER TABLE [identity].RefreshToken ADD CONSTRAINT FK_RefreshToken_Device
        FOREIGN KEY (TenantId, DeviceId) REFERENCES sync.Device (TenantId, Id);

    -- Every uploaded command, keyed by the client's command GUID. A repeated command
    -- returns the stored result instead of being applied twice.
    CREATE TABLE sync.CommandLog
    (
        TenantId        uniqueidentifier NOT NULL,
        Id              uniqueidentifier NOT NULL,   -- client-generated command id
        ClusterKey      bigint IDENTITY(1,1) NOT NULL,
        DeviceId        uniqueidentifier NOT NULL,
        UserId          uniqueidentifier NOT NULL,
        CommandType     varchar(60)      NOT NULL,   -- 'CreateSalesOrder', 'PostGoodsReceipt', 'SubmitCountLines'...
        ClientSequence  bigint           NOT NULL,   -- order of creation on the device
        CreatedOnDeviceAtUtc datetime2(3) NOT NULL,
        PayloadJson     nvarchar(max)    NOT NULL,
        ReceivedAtUtc   datetime2(3)     NOT NULL CONSTRAINT DF_CommandLog_ReceivedAtUtc DEFAULT SYSUTCDATETIME(),
        ProcessedAtUtc  datetime2(3)     NULL,
        Status          varchar(20)      NOT NULL CONSTRAINT DF_CommandLog_Status DEFAULT 'Received',
        ErrorCode       varchar(60)      NULL,
        ResultJson      nvarchar(max)    NULL,
        CONSTRAINT PK_CommandLog PRIMARY KEY NONCLUSTERED (Id),
        CONSTRAINT FK_CommandLog_Device FOREIGN KEY (TenantId, DeviceId) REFERENCES sync.Device (TenantId, Id),
        CONSTRAINT CK_CommandLog_Status CHECK (Status IN ('Received','Applied','AppliedWithChanges','Rejected','Failed')),
        CONSTRAINT CK_CommandLog_Payload_Json CHECK (ISJSON(PayloadJson) = 1),
        CONSTRAINT CK_CommandLog_Result_Json CHECK (ResultJson IS NULL OR ISJSON(ResultJson) = 1)
    );
    CREATE UNIQUE CLUSTERED INDEX CX_CommandLog ON sync.CommandLog (TenantId, ClusterKey);
    CREATE INDEX IX_CommandLog_Device ON sync.CommandLog (TenantId, DeviceId, ClientSequence);

    -- Blocks of document numbers handed to a device so offline receipts carry a final number
    CREATE TABLE sync.DeviceNumberRange
    (
        TenantId        uniqueidentifier NOT NULL,
        Id              uniqueidentifier NOT NULL CONSTRAINT DF_DevRange_Id DEFAULT NEWSEQUENTIALID(),
        ClusterKey      bigint IDENTITY(1,1) NOT NULL,
        DeviceId        uniqueidentifier NOT NULL,
        DocumentType    varchar(40)      NOT NULL,
        Prefix          nvarchar(20)     NOT NULL,
        RangeStart      bigint           NOT NULL,
        RangeEnd        bigint           NOT NULL,
        LastUsedNumber  bigint           NULL,       -- reported back by the device on sync
        IssuedAtUtc     datetime2(3)     NOT NULL CONSTRAINT DF_DevRange_IssuedAtUtc DEFAULT SYSUTCDATETIME(),
        ClosedAtUtc     datetime2(3)     NULL,       -- exhausted or device revoked; unused numbers logged as gaps
        CONSTRAINT PK_DeviceNumberRange PRIMARY KEY NONCLUSTERED (Id),
        CONSTRAINT FK_DevRange_Device FOREIGN KEY (TenantId, DeviceId) REFERENCES sync.Device (TenantId, Id),
        CONSTRAINT CK_DevRange CHECK (RangeEnd >= RangeStart)
    );
    CREATE UNIQUE CLUSTERED INDEX CX_DeviceNumberRange ON sync.DeviceNumberRange (TenantId, ClusterKey);
    CREATE INDEX IX_DevRange_Device ON sync.DeviceNumberRange (TenantId, DeviceId, DocumentType) WHERE ClosedAtUtc IS NULL;

    -- Rows physically deleted from synced tables (most use IsActive instead)
    CREATE TABLE sync.Tombstone
    (
        TenantId        uniqueidentifier NOT NULL,
        Id              bigint IDENTITY(1,1) NOT NULL,
        EntityName      varchar(100)     NOT NULL,
        EntityId        uniqueidentifier NOT NULL,
        DeletedAtUtc    datetime2(3)     NOT NULL CONSTRAINT DF_Tombstone_DeletedAtUtc DEFAULT SYSUTCDATETIME(),
        RowVer          rowversion       NOT NULL,
        CONSTRAINT PK_Tombstone PRIMARY KEY NONCLUSTERED (Id)
    );
    CREATE UNIQUE CLUSTERED INDEX CX_Tombstone ON sync.Tombstone (TenantId, Id);
    CREATE INDEX IX_Tombstone_Sync ON sync.Tombstone (TenantId, RowVer);

    -- Global (not tenant-owned): forces app updates
    CREATE TABLE sync.AppVersionPolicy
    (
        Platform        varchar(10)      NOT NULL,
        MinVersion      varchar(20)      NOT NULL,   -- below this the app must update
        LatestVersion   varchar(20)      NOT NULL,
        StoreUrl        nvarchar(400)    NULL,
        UpdatedAtUtc    datetime2(3)     NOT NULL CONSTRAINT DF_AppVersion_UpdatedAtUtc DEFAULT SYSUTCDATETIME(),
        CONSTRAINT PK_AppVersionPolicy PRIMARY KEY CLUSTERED (Platform),
        CONSTRAINT CK_AppVersion_Platform CHECK (Platform IN ('Android','iOS'))
    );

    INSERT dbo.SchemaVersion (ScriptName) VALUES (N'008_Sync');
    COMMIT TRANSACTION;
    PRINT N'008_Sync applied.';
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
